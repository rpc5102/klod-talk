// Turns docs/reference/words.json into hooks/words.ts, because a hooks
// module imports only script files. Run from the repo root:
//
//   node scripts/gen-words.mjs          write hooks/words.ts
//   node scripts/gen-words.mjs --check  fail if hooks/words.ts is stale

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const source = join(root, 'docs', 'reference', 'words.json')
const target = join(root, 'hooks', 'words.ts')

const list = JSON.parse(readFileSync(source, 'utf8'))

function fail(message) {
  console.error(`gen-words: ${message}`)
  process.exit(1)
}

const seen = new Set()
for (const words of Object.values(list.groups)) {
  for (const [term, cave] of Object.entries(words)) {
    if (typeof cave !== 'string' || cave.trim() === '') fail(`${term} has no cave word`)
    if (seen.has(term.toLowerCase())) fail(`${term} is listed twice`)
    seen.add(term.toLowerCase())
  }
}

const lines = []
lines.push('// Generated by scripts/gen-words.mjs from docs/reference/words.json. Do not edit by')
lines.push('// hand: change the list and run `node scripts/gen-words.mjs` again.')
lines.push('')
lines.push('/** A term and its cave word: the same cave word for the term, every time. */')
lines.push('export type Word = readonly [term: string, cave: string]')
lines.push('')
lines.push('export type WordGroup = { readonly name: string; readonly words: readonly Word[] }')
lines.push('')
lines.push('export const WORD_GROUPS: readonly WordGroup[] = [')
for (const [name, words] of Object.entries(list.groups)) {
  lines.push('  {')
  lines.push(`    name: ${JSON.stringify(name)},`)
  lines.push('    words: [')
  for (const [term, cave] of Object.entries(words)) {
    lines.push(`      [${JSON.stringify(term)}, ${JSON.stringify(cave)}],`)
  }
  lines.push('    ],')
  lines.push('  },')
}
lines.push(']')
lines.push('')
lines.push('/** Every word of every group, in the list\'s order. */')
lines.push('export const WORDS: readonly Word[] = WORD_GROUPS.flatMap(group => group.words)')
lines.push('')

const text = lines.join('\n')
if (process.argv.includes('--check')) {
  let current = ''
  try {
    current = readFileSync(target, 'utf8')
  } catch {
    fail('hooks/words.ts is missing')
  }
  if (current !== text) fail('hooks/words.ts is stale: run node scripts/gen-words.mjs')
  console.log('gen-words: hooks/words.ts is up to date')
} else {
  writeFileSync(target, text)
  console.log(`gen-words: wrote hooks/words.ts (${seen.size} words)`)
}
