// Turns the sprite kit's caveman.json into hooks/catalog.ts, because a hooks
// module imports only script files. Run from the repo root:
//
//   node scripts/gen-catalog.mjs          write hooks/catalog.ts
//   node scripts/gen-catalog.mjs --check  fail if hooks/catalog.ts is stale

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const source = join(root, 'kit', 'caveman.json')
const target = join(root, 'hooks', 'catalog.ts')

const kit = JSON.parse(readFileSync(source, 'utf8'))

function fail(message) {
  console.error(`gen-catalog: ${message}`)
  process.exit(1)
}

// Check the kit before writing anything, so a bad edit to the JSON fails here
// rather than drawing a broken frame later.
const width = kit.frame_width
const height = kit.frame_height
if (height % 2 !== 0) fail('frame height must be even: the terminal packs two pixels per cell')
for (const [name, pose] of Object.entries(kit.poses)) {
  if (pose.frames.length !== pose.durations_ms.length) {
    fail(`${name}: ${pose.frames.length} frames but ${pose.durations_ms.length} durations`)
  }
  for (const [index, frame] of pose.frames.entries()) {
    if (frame.length !== height) fail(`${name} frame ${index}: ${frame.length} rows, not ${height}`)
    for (const row of frame) {
      if (row.length !== width) fail(`${name} frame ${index}: a row of ${row.length}, not ${width}`)
      for (const char of row) {
        if (char !== kit.transparent && !(char in kit.palette)) {
          fail(`${name} frame ${index}: '${char}' is not in the palette`)
        }
      }
    }
  }
}

const hex = color => `0x${color.slice(1).toLowerCase()}`
const lines = []
lines.push('// Generated by scripts/gen-catalog.mjs from kit/caveman.json. Do not edit by hand:')
lines.push('// change the kit and run `node scripts/gen-catalog.mjs` again.')
lines.push('')
lines.push("import type { PoseName } from '../types'")
lines.push('')
lines.push('/** One frame: rows of pixels, one character per pixel, the transparent one included. */')
lines.push('export type Grid = readonly string[]')
lines.push('')
lines.push('export type Pose = {')
lines.push('  readonly description: string')
lines.push('  readonly durationsMs: readonly number[]')
lines.push('  readonly frames: readonly Grid[]')
lines.push('}')
lines.push('')
lines.push('export type Catalog = {')
lines.push('  readonly width: number')
lines.push('  readonly height: number')
lines.push('  readonly transparent: string')
lines.push('  /** Pixel character to 0xRRGGBB. */')
lines.push('  readonly palette: Readonly<Record<string, number>>')
lines.push('  readonly poses: Readonly<Record<PoseName, Pose>>')
lines.push('}')
lines.push('')
lines.push('export const CATALOG: Catalog = {')
lines.push(`  width: ${width},`)
lines.push(`  height: ${height},`)
lines.push(`  transparent: ${JSON.stringify(kit.transparent)},`)
lines.push('  palette: {')
for (const [char, color] of Object.entries(kit.palette)) {
  lines.push(`    ${JSON.stringify(char)}: ${hex(color)},`)
}
lines.push('  },')
lines.push('  poses: {')
for (const [name, pose] of Object.entries(kit.poses)) {
  lines.push(`    ${name}: {`)
  lines.push(`      description: ${JSON.stringify(pose.description)},`)
  lines.push(`      durationsMs: [${pose.durations_ms.join(', ')}],`)
  lines.push('      frames: [')
  for (const frame of pose.frames) {
    lines.push('        [')
    for (const row of frame) lines.push(`          ${JSON.stringify(row)},`)
    lines.push('        ],')
  }
  lines.push('      ],')
  lines.push('    },')
}
lines.push('  },')
lines.push('}')
lines.push('')

const text = lines.join('\n')
if (process.argv.includes('--check')) {
  let current = ''
  try {
    current = readFileSync(target, 'utf8')
  } catch {
    fail('hooks/catalog.ts is missing')
  }
  if (current !== text) fail('hooks/catalog.ts is stale: run node scripts/gen-catalog.mjs')
  console.log('gen-catalog: hooks/catalog.ts is up to date')
} else {
  writeFileSync(target, text)
  console.log(`gen-catalog: wrote hooks/catalog.ts (${Object.keys(kit.poses).length} poses)`)
}
