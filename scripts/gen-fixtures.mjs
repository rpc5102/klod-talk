// Turns the prototypes' scene data and the sample answers into
// tests/fixtures.ts, because a test runs where it cannot read files. Run from
// the repo root:
//
//   node scripts/gen-fixtures.mjs          write tests/fixtures.ts
//   node scripts/gen-fixtures.mjs --check  fail if tests/fixtures.ts is stale

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const target = join(root, 'tests', 'fixtures.ts')
const load = path => JSON.parse(readFileSync(join(root, path), 'utf8'))

const a2 = load('docs/prototypes/a2-stone-tablet.json')
const a3 = load('docs/prototypes/a3-live-session.json')
const samples = load('docs/reference/samples.json')

const segments = paragraph => paragraph.map(([text, isTerm]) => ({ text, isTerm: isTerm === 1 }))
const scene = one => ({ id: one.id, sprite: one.sprite, status: one.status, meta: one.meta })
const levels = list =>
  list.map(level => ({
    name: level.name,
    status: level.status,
    takes: level.takes.map(take => take.map(segments)),
  }))

const data = {
  A2: { scenes: a2.scenes.map(scene), levels: levels(a2.levels) },
  A3: {
    prompt: a3.prompt,
    chew: { sprite: a3.chew.sprite, status: a3.chew.status, meta: a3.chew.meta },
    scenes: a3.scenes.map(scene),
    levels: levels(a3.levels),
  },
  SAMPLES: samples.samples.map(sample => ({
    id: sample.id,
    chat: sample.chat,
    cave: sample.cave,
    mammoths: sample.mammoths,
  })),
  STATUS_LINES: samples.status_lines,
}

const lines = [
  '// Generated by scripts/gen-fixtures.mjs from docs/prototypes/ and',
  '// docs/reference/samples.json. Do not edit by hand.',
  '',
  'export type Seg = { text: string; isTerm: boolean }',
  'export type Scene = { id: string; sprite: string; status: string; meta: string }',
  'export type Level = { name: string; status: string; takes: Seg[][][] }',
  'export type Sample = { id: string; chat: string; cave: string[]; mammoths: number }',
  '',
  `export const A2: { scenes: Scene[]; levels: Level[] } = ${JSON.stringify(data.A2, null, 2)}`,
  '',
  'export const A3: {',
  '  prompt: string',
  '  chew: { sprite: string; status: string; meta: string }',
  '  scenes: Scene[]',
  '  levels: Level[]',
  `} = ${JSON.stringify(data.A3, null, 2)}`,
  '',
  `export const SAMPLES: Sample[] = ${JSON.stringify(data.SAMPLES, null, 2)}`,
  '',
  `export const STATUS_LINES: Record<string, string> = ${JSON.stringify(data.STATUS_LINES, null, 2)}`,
  '',
]

const text = lines.join('\n')
if (process.argv.includes('--check')) {
  let current = ''
  try {
    current = readFileSync(target, 'utf8')
  } catch {
    console.error('gen-fixtures: tests/fixtures.ts is missing')
    process.exit(1)
  }
  if (current !== text) {
    console.error('gen-fixtures: tests/fixtures.ts is stale: run node scripts/gen-fixtures.mjs')
    process.exit(1)
  }
  console.log('gen-fixtures: tests/fixtures.ts is up to date')
} else {
  writeFileSync(target, text)
  console.log('gen-fixtures: wrote tests/fixtures.ts')
}
